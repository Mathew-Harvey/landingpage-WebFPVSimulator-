import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));

/* Load articles dynamically */
const { ARTICLES } = await import('../src/wiki/articles.js');
const { allCliPages, cliIndexPage } = await import('../src/wiki/cli.js');

/* Load indexing config */
const indexConfig = JSON.parse(readFileSync(join(root, 'wiki-index-config.json'), 'utf8'));

function slugify(id) {
  return id;
}

function generateMetaDescription(article) {
  /* Use lede as meta description, truncated to 155 chars */
  const lede = article.lede || '';
  if (lede.length <= 155) {
    return lede;
  }
  return lede.slice(0, 152) + '...';
}

function shouldIndex(articleId) {
  if (indexConfig.globalIndexing) {
    return true;
  }
  return indexConfig.allowIndexing.includes(articleId);
}

function generateArticlePage(article) {
  const slug = slugify(article.id);
  const url = `https://webfpv.org/wiki/${slug}/`;
  const title = `${article.title}, FPV wiki`;
  const description = generateMetaDescription(article);
  const indexed = shouldIndex(article.id);
  
  const robotsMeta = indexed 
    ? '' 
    : '    <meta name="robots" content="noindex">\n';

  const html = `<!doctype html>
<!--
  FPV wiki article: ${article.title}
  
  This page is GENERATED by scripts/generate-wiki-pages.js.
  DO NOT EDIT THIS FILE DIRECTLY. Edit src/wiki/articles.js instead.
  
  This file is part of the WebFPVSimulator landing page.

  This program is free software: you can redistribute it and/or modify
  it under the terms of the GNU General Public License as published by
  the Free Software Foundation, either version 3 of the License, or (at
  your option) any later version.

  This program is distributed in the hope that it will be useful, but
  WITHOUT ANY WARRANTY; without even the implied warranty of
  MERCHANTABILITY or FITNESS FOR A PARTICULAR PURPOSE. See the GNU
  General Public License for more details.

  You should have received a copy of the GNU General Public License
  along with this program. If not, see <https://www.gnu.org/licenses/>.
-->
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${title}</title>
    <meta name="description" content="${description}" />
${robotsMeta}    <meta name="theme-color" content="#141c16" />
    <link rel="canonical" href="${url}" />
    <meta property="og:type" content="article" />
    <meta property="og:site_name" content="WebFPV" />
    <meta property="og:url" content="${url}" />
    <meta property="og:title" content="${title}" />
    <meta property="og:description" content="${description}" />
    <meta property="og:image" content="https://webfpv.org/og.png" />
    <meta property="og:image:type" content="image/png" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="A five inch racing quad on a lit studio deck, its frame open and the stack visible." />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="${title}" />
    <meta name="twitter:description" content="${description}" />
    <meta name="twitter:image" content="https://webfpv.org/og.png" />
    <link rel="icon" href="../../icon.svg" type="image/svg+xml" />
    <link rel="icon" href="../../favicon.ico" sizes="32x32" />
    <link rel="apple-touch-icon" href="../../apple-touch-icon.png" />
    <script type="application/ld+json">
{
  "@context": "https://schema.org",
  "@type": "Article",
  "headline": "${article.title}",
  "description": "${description.replace(/"/g, '\\"')}",
  "url": "${url}",
  "isPartOf": {
    "@type": "WebSite",
    "name": "WebFPV",
    "url": "https://webfpv.org/"
  },
  "about": {
    "@type": "Thing",
    "name": "FPV drone racing physics and flight controller"
  }
}
    </script>
    <script type="module">
      /* Redirect to the wiki SPA with the article pre-loaded */
      window.location.href = '/wiki/#wiki/${article.id}';
    </script>
  </head>
  <body>
    <noscript>
      <h1>${article.title}</h1>
      <p>${article.lede}</p>
      <p><a href="/wiki/">View in the interactive wiki</a></p>
    </noscript>
  </body>
</html>
`;
  
  return { slug, html };
}

/* Generate directory structure and pages */
const wikiDir = join(root, 'wiki');
const articles = [];

for (const article of ARTICLES) {
  const { slug, html } = generateArticlePage(article);
  const articleDir = join(wikiDir, slug);
  
  if (!existsSync(articleDir)) {
    mkdirSync(articleDir, { recursive: true });
  }
  
  const filepath = join(articleDir, 'index.html');
  writeFileSync(filepath, html, 'utf8');
  
  articles.push({
    id: article.id,
    slug,
    url: `https://webfpv.org/wiki/${slug}/`,
    indexed: shouldIndex(article.id),
  });
}

