const MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
const LONG = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

const fmt = (n) => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, ',');
const f = (n) => n.toFixed(1);
const short = (iso) => `${Number(iso.slice(8))} ${MONTHS[Number(iso.slice(5, 7)) - 1]}`;
const long = (iso) => `${Number(iso.slice(8))} ${LONG[Number(iso.slice(5, 7)) - 1]}`;
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/*
 * The plot is drawn in a viewBox of exactly these units and scaled uniformly,
 * so a circle stays a circle and a rounded bar keeps its corner at any width.
 * Every word on the graph is HTML at a fixed size, placed by percentages of
 * the plot: a phone gets text it can read, not a shrunken copy of the
 * desktop's. The margins for those words are the page's CSS, not geometry.
 */
export const geometry = { pw: 420, aH: 190, bH: 110, gap: 2 };

function niceScale(max, want) {
  const raw = Math.max(max, 1) / want;
  const mag = 10 ** Math.floor(Math.log10(raw));
  const step = [1, 2, 2.5, 5, 10].map((m) => m * mag).find((s) => s >= raw);
  return { step, top: Math.ceil(Math.max(max, 1) / step) * step };
}

export function lastDay(data) {
  return new Date(Date.parse(`${data.first}T00:00:00Z`) + (data.days - 1) * 86400000).toISOString().slice(0, 10);
}

/* Which days get a date under the bars: every seventh counting back from the
   newest while the span is short, then the first of each month, thinned to
   about eight. Oldest first. */
function tickDays(days) {
  const n = days.length;
  if (n <= 70) {
    const out = [];
    for (let i = n - 1; i >= 0; i -= 7) {
      out.push(i);
    }
    return out.reverse();
  }
  const firsts = days.flatMap((d, i) => (d.endsWith('-01') ? [i] : []));
  const every = Math.max(1, Math.ceil(firsts.length / 8));
  return firsts.filter((_, k) => k % every === 0);
}

export function render(data) {
  const { pw, aH, bH, gap } = geometry;
  const ids = REPOS.map((r) => r.id);
  const names = Object.fromEntries(REPOS.map((r) => [r.id, r.name]));
  const ends = Object.fromEntries(REPOS.map((r) => [r.id, r.end]));
  const n = data.days;
  const days = daysBetween(data.first, lastDay(data));
  const slot = pw / n;
  const xAt = (i) => (i + 0.5) * slot;
  const pctX = (x) => `${f((x / pw) * 100)}%`;
  const lastI = n - 1;
  const multiYear = days[0].slice(0, 4) !== days[lastI].slice(0, 4);
  const dayLabel = (iso) => (multiYear ? `${short(iso)} ${iso.slice(0, 4)}` : short(iso));

  const total = days.map((_, i) => ids.reduce((s, id) => s + data.lines[id][i], 0));
  const perDay = days.map((_, i) => ids.reduce((s, id) => s + data.commits[id][i], 0));
  const commitsAll = perDay.reduce((s, v) => s + v, 0);
  const peakI = perDay.indexOf(Math.max(...perDay));

  /* ---- panel A: lines, stacked, cumulative ---- */
  const sa = niceScale(Math.max(...total), 3);
  const yA = (v) => aH * (1 - v / sa.top);
  const pctA = (y) => `${f((y / aH) * 100)}%`;
  const X = [0, ...days.map((_, i) => xAt(i))];
  const stack = [X.map(() => 0)];
  for (const id of ids) {
    const prev = stack[stack.length - 1];
    stack.push([0, ...data.lines[id]].map((v, j) => prev[j] + v));
  }
  let a = '';
  let aTicks = '';
  for (let t = 0; t <= sa.top; t += sa.step) {
    a += `<line class="${t === 0 ? 'ax' : 'g'}" x1="0" x2="${pw}" y1="${f(yA(t))}" y2="${f(yA(t))}"/>`;
    aTicks += `<span class="yt" style="top:${pctA(yA(t))}">${fmt(t)}</span>`;
  }
  ids.forEach((id, k) => {
    const top = X.map((x, j) => [x, yA(stack[k + 1][j])]);
    const bot = X.map((x, j) => [x, k === 0 ? yA(0) : yA(stack[k][j]) - gap]);
    const clamped = top.map(([x, y], j) => [x, Math.min(y, bot[j][1])]);
    const pts = (p) => p.map(([x, y]) => `${f(x)} ${f(y)}`).join('L');
    a += `<path class="fa s-${id}" d="M${pts(clamped)}L${pts([...bot].reverse())}Z"/>`;
  });
  for (let k = ids.length - 1; k >= 0; k -= 1) {
    a += `<path class="la s-${ids[k]}" d="M${X.map((x, j) => `${f(x)} ${f(yA(stack[k + 1][j]))}`).join('L')}"/>`;
  }
  /* The end labels ride the layers, and a label that would sit on another is dropped: the key and the tooltip carry it. */
  let labels = '';
  let lastY = Infinity;
  for (let k = 0; k < ids.length; k += 1) {
    const mid = (yA(stack[k + 1][n]) + yA(stack[k][n])) / 2;
    if (lastY === Infinity || lastY - mid >= 14) {
      labels += `<span class="lb s-${ids[k]}" style="top:${pctA(mid)}"><i class="k"></i>${esc(ends[ids[k]])}</span>`;
      lastY = mid;
    }
  }
  const topY = yA(total[lastI]);
  const end = `<span class="mk" style="left:${pctX(X[n])};top:${pctA(topY)}"></span><span class="val" style="top:${pctA(topY)}">${fmt(total[lastI])} lines</span>`;

  /* ---- panel B: commits a day, stacked bars ---- */
  const sb = niceScale(Math.max(...perDay), 4);
  const yB = (v) => bH * (1 - v / sb.top);
  const pctB = (y) => `${f((y / bH) * 100)}%`;
  const bw = Math.min(24, Math.max(slot * 0.72, slot - 2));
  let bars = '';
  let bTicks = '';
  for (let t = 0; t <= sb.top; t += sb.step) {
    bars += `<line class="${t === 0 ? 'ax' : 'g'}" x1="0" x2="${pw}" y1="${f(yB(t))}" y2="${f(yB(t))}"/>`;
    bTicks += `<span class="yt" style="top:${pctB(yB(t))}">${fmt(t)}</span>`;
  }
  const per = bH / sb.top;
  days.forEach((_, i) => {
    const segs = ids.map((id) => ({ id, v: data.commits[id][i] })).filter((s) => s.v > 0);
    let y = yB(0);
    segs.forEach((s, k) => {
      const h = Math.max(s.v * per, 1.5);
      const top = k === segs.length - 1;
      const drawn = top || h <= gap + 1 ? h : h - gap;
      const x0 = xAt(i) - bw / 2;
      const x1 = x0 + bw;
      const y0 = y;
      const y1 = y - drawn;
      if (top) {
        const r = Math.min(4, bw / 2, drawn);
        bars += `<path class="bar s-${s.id}" d="M${f(x0)} ${f(y0)}V${f(y1 + r)}Q${f(x0)} ${f(y1)} ${f(x0 + r)} ${f(y1)}H${f(x1 - r)}Q${f(x1)} ${f(y1)} ${f(x1)} ${f(y1 + r)}V${f(y0)}Z"/>`;
      } else {
        bars += `<rect class="bar s-${s.id}" x="${f(x0)}" y="${f(y1)}" width="${f(bw)}" height="${f(drawn)}"/>`;
      }
      y -= h;
    });
  });
  /* The peak's label is centred on its bar, unless the bar is near an end, where it hangs inward so it never leaves the plot. */
  const side = xAt(peakI) > pw * 0.7 ? 'r' : xAt(peakI) < pw * 0.3 ? 'l' : '';
  const peakX = xAt(peakI) + (side === 'r' ? bw / 2 : side === 'l' ? -bw / 2 : 0);
  const peak = `<span class="pk${side ? ` ${side}` : ''}" style="left:${pctX(peakX)};top:${pctB(yB(perDay[peakI]))}">${perDay[peakI]} on ${short(days[peakI])}</span>`;
  const marks = tickDays(days);
  let xs = '';
  marks.forEach((i, k) => {
    const alt = (marks.length - 1 - k) % 2 ? ' alt' : '';
    bars += `<line class="tick" x1="${f(xAt(i))}" x2="${f(xAt(i))}" y1="${bH}" y2="${bH + 5}"/>`;
    const withYear = multiYear || n > 70 ? days[i].slice(5, 7) === '01' : false;
    xs += `<span class="xt${alt}" style="left:${pctX(xAt(i))}">${withYear ? `${short(days[i])} ${days[i].slice(0, 4)}` : short(days[i])}</span>`;
  });

  /* ---- the key, the table, the words ---- */
  const key = ids.map((id) => `<li><span class="sw s-${id}"></span>${esc(names[id])} <span class="num">${fmt(data.lines[id][lastI])}</span></li>`).join('');
  const rows = [];
  for (let i = lastI; i >= 0; i -= 1) {
    const cells = [...ids.map((id) => data.lines[id][i]), total[i], ...ids.map((id) => data.commits[id][i]), perDay[i]];
    rows.push(`<tr><th scope="row">${dayLabel(days[i])}</th>${cells.map((v) => `<td>${fmt(v)}</td>`).join('')}</tr>`);
  }
  const summary = `Lines of source grew from ${fmt(total[0])} on ${long(days[0])} to ${fmt(total[lastI])} on ${long(days[lastI])}: ${ids.map((id) => `${names[id].toLowerCase()} ${fmt(data.lines[id][lastI])}`).join(', ')}.`;
  const busiest = `Commits a day, most on ${long(days[peakI])} with ${perDay[peakI]}. The table view has every day.`;
  const year = days[lastI].slice(0, 4);

  return [
    '<section id="velocity">',
    '  <h2>Velocity</h2>',
    `  <p class="when">${long(days[0])} to ${long(days[lastI])} ${year}</p>`,
    `  <p class="lede">${fmt(total[lastI])} lines of source after ${n} days, from ${fmt(commitsAll)} commits across the simulator, the board and this site.</p>`,
    '  <figure class="viz">',
    `    <ul class="key">${key}</ul>`,
    `    <div class="plots" tabindex="0" role="group" aria-label="Velocity graph. Use the left and right arrow keys to read one day at a time." data-n="${n}" data-ids="${ids.join(',')}">`,
    `      <div class="panel a" role="img" aria-label="${esc(summary)}">`,
    '        <p class="viz-h">Lines of source, at the end of each day</p>',
    '        <div class="frame">',
    `          <div class="plot" style="aspect-ratio:${pw}/${aH}">`,
    `            <svg viewBox="0 0 ${pw} ${aH}" focusable="false">${a}</svg>`,
    `            ${aTicks}${labels}${end}`,
    '          </div>',
    '        </div>',
    '      </div>',
    `      <div class="panel b" role="img" aria-label="${esc(busiest)}">`,
    '        <p class="viz-h">Commits a day</p>',
    '        <div class="frame">',
    `          <div class="plot" style="aspect-ratio:${pw}/${bH}">`,
    `            <svg viewBox="0 0 ${pw} ${bH}" focusable="false">`,
    '              <defs>',
    ...ids.map((id, k) => `                <pattern id="vel-p-${id}" width="6" height="6" patternUnits="userSpaceOnUse" patternTransform="rotate(${k === 1 ? 135 : 45})"><path d="M0 0V6" stroke="CanvasText" stroke-width="1.6"/>${k === 2 ? '<path d="M0 0H6" stroke="CanvasText" stroke-width="1.6"/>' : ''}</pattern>`),
    '              </defs>',
    `              ${bars}`,
    '            </svg>',
    `            ${bTicks}${peak}${xs}`,
    '          </div>',
    '        </div>',
    '      </div>',
    '      <div class="cross" hidden></div>',
    '      <div class="tip" hidden></div>',
    '      <p class="sr" aria-live="polite"></p>',
    '    </div>',
    `    <figcaption>Lines of source are the hand written .js, .mjs, .c, .h, .html and .css files on each repository's main branch, added up from its git history. Not counted: code that is not ours, files a script writes, the simulator's files copied into the board and this site, the wiki's generated pages, and this page. Commits are non merge commits by author date. Days are Perth time.</figcaption>`,
    '    <details class="viz-table">',
    '      <summary>Table view</summary>',
    '      <div class="scroll" tabindex="0">',
    '        <table>',
    '          <caption>Lines of source at the end of each day, and commits made that day, newest first.</caption>',
    '          <thead><tr><th rowspan="2" scope="col">Day</th><th colspan="4" scope="colgroup">Lines of source</th><th colspan="4" scope="colgroup">Commits</th></tr>',
    `          <tr>${ids.map((id) => `<th scope="col">${esc(names[id])}</th>`).join('')}<th scope="col">All</th>${ids.map((id) => `<th scope="col">${esc(names[id])}</th>`).join('')}<th scope="col">All</th></tr></thead>`,
    `          <tbody>${rows.join('')}</tbody>`,
    '        </table>',
    '      </div>',
    '    </details>',
    '  </figure>',
    '</section>',
  ].join('\n');
}

/* What sits in the page, markers included, indented as the page's sections are. */
export function block(data) {
  const body = render(data).split('\n').map((l) => (l ? `      ${l}` : l)).join('\n');
  return `      ${BEGIN}\n${body}\n      ${END}`;
}

export function splice(page, data) {
  const fresh = block(data);
  const at = page.indexOf(`      ${BEGIN}`);
  if (at !== -1) {
    const end = page.indexOf(END, at);
    if (end === -1) {
      throw new Error('the velocity begin marker has no end marker');
    }
    return page.slice(0, at) + fresh + page.slice(end + END.length);
  }
  /* A page with no graph yet gets it directly under the jump list, above the first entry. */
  const nav = page.indexOf('<nav class="weeks"');
  const close = nav === -1 ? -1 : page.indexOf('</nav>', nav);
  if (close === -1) {
    throw new Error('no jump list (nav.weeks) to put the graph under');
  }
  const after = close + '</nav>'.length;
  return `${page.slice(0, after)}\n\n${fresh}${page.slice(after)}`;
}

