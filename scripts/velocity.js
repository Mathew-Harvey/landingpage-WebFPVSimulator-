async function main() {
  const args = process.argv.slice(2);
  if (args[0] === '--check') {
    const data = JSON.parse(await readFile(join(root, DATA), 'utf8'));
    const page = await readFile(join(root, PAGE), 'utf8');
    const ok = page.includes(block(data)) && page.split(BEGIN).length === 2;
    console.log(ok ? 'the page says what notes/velocity.json says' : 'the page and notes/velocity.json disagree: run scripts/velocity.js');
    process.exit(ok ? 0 : 1);
  }
  if (args.length !== 2) {
    console.error('usage: node scripts/velocity.js <simulator checkout> <board checkout>\n       node scripts/velocity.js --check');
    process.exit(2);
  }
  const data = collect({ sim: resolve(args[0]), board: resolve(args[1]), site: root });
  await writeFile(join(root, DATA), stringify(data));
  const page = await readFile(join(root, PAGE), 'utf8');
  await writeFile(join(root, PAGE), splice(page, data));
  const last = data.days - 1;
  for (const id of REPOS.map((r) => r.id)) {
    console.log(`${id.padEnd(6)} ${String(data.lines[id][last]).padStart(8)} lines  ${String(data.commits[id].reduce((s, v) => s + v, 0)).padStart(5)} commits  at ${data.heads[id]}`);
  }
  console.log(`${data.first} to ${lastDay(data)}, ${data.days} days, written to ${DATA} and ${PAGE}`);
}

