function git(cwd, args) {
  return execFileSync('git', args, { cwd, encoding: 'utf8', maxBuffer: 1 << 30 });
}

function refOf(cwd) {
  for (const ref of ['origin/main', 'main', 'HEAD']) {
    try {
      git(cwd, ['rev-parse', '--verify', '-q', `${ref}^{commit}`]);
      return ref;
    } catch (e) {
      /* Not there. Try the next. */
    }
  }
  throw new Error(`${cwd}: no origin/main, main or HEAD`);
}

function pathspec(repo) {
  const skip = repo.skip.map(([p]) => `:(exclude${p.includes('*') ? ',glob' : ''})${p}`);
  return [...EXTENSIONS.map((e) => `*.${e}`), ...skip];
}

export function dayOf(unixSeconds) {
  return new Date((unixSeconds + UTC_OFFSET_HOURS * 3600) * 1000).toISOString().slice(0, 10);
}

function directCount(cwd, ref, spec) {
  let out = '';
  try {
    out = git(cwd, ['grep', '-I', '-c', '', ref, '--', ...spec]);
  } catch (e) {
    return 0; /* git grep exits 1 when nothing matches. */
  }
  let n = 0;
  for (const line of out.split('\n')) {
    if (line) {
      n += Number(line.slice(line.lastIndexOf(':') + 1));
    }
  }
  return n;
}

function measure(repo, cwd) {
  if (git(cwd, ['rev-parse', '--is-shallow-repository']).trim() === 'true') {
    throw new Error(`${cwd} is a shallow clone. Fetch its whole history first: git fetch --unshallow`);
  }
  const ref = refOf(cwd);
  const spec = pathspec(repo);

  const net = new Map();
  let day = null;
  const stat = git(cwd, ['log', ref, '--first-parent', '-m', '--no-renames', '--numstat', '--format=@%at', '--', ...spec]);
  for (const line of stat.split('\n')) {
    if (line.startsWith('@')) {
      day = dayOf(Number(line.slice(1)));
      continue;
    }
    const m = /^(\d+|-)\t(\d+|-)\t/.exec(line);
    if (m && day) {
      const add = m[1] === '-' ? 0 : Number(m[1]);
      const del = m[2] === '-' ? 0 : Number(m[2]);
      net.set(day, (net.get(day) || 0) + add - del);
    }
  }

  const commits = new Map();
  for (const t of git(cwd, ['log', ref, '--no-merges', '--format=%at']).split('\n')) {
    if (t) {
      const d = dayOf(Number(t));
      commits.set(d, (commits.get(d) || 0) + 1);
    }
  }

  const summed = [...net.values()].reduce((s, v) => s + v, 0);
  const direct = directCount(cwd, ref, spec);
  if (summed !== direct) {
    throw new Error(`${repo.id}: the history sums to ${summed} lines but the files at ${ref} hold ${direct}`);
  }
  return { net, commits, head: git(cwd, ['rev-parse', '--short=8', ref]).trim(), ref, total: direct };
}

function daysBetween(first, last) {
  const out = [];
  for (let t = Date.parse(`${first}T00:00:00Z`); t <= Date.parse(`${last}T00:00:00Z`); t += 86400000) {
    out.push(new Date(t).toISOString().slice(0, 10));
  }
  return out;
}

export function collect(paths) {
  const got = REPOS.map((r) => ({ repo: r, ...measure(r, paths[r.id]) }));
  const seen = got.flatMap((g) => [...g.net.keys(), ...g.commits.keys()]).sort();
  const days = daysBetween(seen[0], seen[seen.length - 1]);
  const lines = {};
  const commits = {};
  const heads = {};
  for (const g of got) {
    let run = 0;
    lines[g.repo.id] = days.map((d) => (run += g.net.get(d) || 0));
    commits[g.repo.id] = days.map((d) => g.commits.get(d) || 0);
    heads[g.repo.id] = g.head;
  }
  return {
    generated: 'scripts/velocity.js',
    heads,
    zone: `Perth, UTC+${UTC_OFFSET_HOURS}`,
    counted: EXTENSIONS,
    repos: REPOS.map((r) => ({ id: r.id, name: r.name, notCounted: r.skip.map(([path, why]) => ({ path, why })) })),
    first: days[0],
    days: days.length,
    lines,
    commits,
  };
}

/* One line per array, so a diff of the data reads as a diff of numbers. */
export function stringify(data) {
  const arr = (a) => `[${a.join(', ')}]`;
  const group = (o) => `{\n${Object.entries(o).map(([k, v]) => `    ${JSON.stringify(k)}: ${arr(v)}`).join(',\n')}\n  }`;
  const rest = { ...data };
  delete rest.lines;
  delete rest.commits;
  delete rest.repos;
  const head = Object.entries(rest).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)}`);
  const repos = `[\n${data.repos.map((r) => `    ${JSON.stringify(r)}`).join(',\n')}\n  ]`;
  return `{\n${head.join(',\n')},\n  "repos": ${repos},\n  "lines": ${group(data.lines)},\n  "commits": ${group(data.commits)}\n}\n`;
}

